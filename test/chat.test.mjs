import { test } from "node:test";
import assert from "node:assert/strict";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { lastClaudeChat, redact } from "../src/chat.mjs";

function home(t) {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), "waitu-chat-"));
  t.after(() => fs.rmSync(dir, { recursive: true, force: true }));
  return dir;
}

// Writes a Claude Code style session log: one JSON line per message.
function session(dir, name, cwd, messages, ageMinutes = 0) {
  const file = path.join(dir, ".claude", "projects", name, "s.jsonl");
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, messages.map(([type, content, extra = {}]) => JSON.stringify({ type, cwd, message: { role: type, content }, ...extra })).join("\n") + "\n");
  const time = new Date(Date.now() - ageMinutes * 60000);
  fs.utimesSync(file, time, time);
  return file;
}

const project = path.resolve(os.tmpdir(), "shop");

test("reads the first request, the latest ones and Claude's last reply for this project", (t) => {
  const dir = home(t);
  session(dir, "shop", project, [
    ["user", "Add a pricing section to the landing page"],
    ["assistant", [{ type: "text", text: "I'll start with the layout." }, { type: "tool_use", name: "Edit", input: {} }]],
    ["user", [{ type: "tool_result", content: "file written" }]],
    ["user", "<command-name>/compact</command-name>"],
    ["user", "Caveat: The messages below were generated by the user while running local commands.", { isMeta: true }],
    ["user", [{ type: "text", text: "Make the yearly plan cheaper" }]],
    ["assistant", [{ type: "text", text: "Pricing cards are done; the FAQ below them is still empty." }]],
  ]);
  const chat = lastClaudeChat({ home: dir, cwd: project });
  assert.equal(chat.task, "Add a pricing section to the landing page");
  assert.deepEqual(chat.recent, ["Make the yearly plan cheaper"]);
  assert.equal(chat.lastReply, "Pricing cards are done; the FAQ below them is still empty.");
  assert.equal(chat.requests, 2);
});

test("a newer chat from another project is not used", (t) => {
  const dir = home(t);
  session(dir, "shop", project, [["user", "Fix the cart total"]], 30);
  session(dir, "blog", path.resolve(os.tmpdir(), "blog"), [["user", "Write the about page"]], 1);
  assert.equal(lastClaudeChat({ home: dir, cwd: project }).task, "Fix the cart total");
});

test("no Claude Code chat for the project gives null", (t) => {
  const dir = home(t);
  assert.equal(lastClaudeChat({ home: dir, cwd: project }), null);
  session(dir, "blog", path.resolve(os.tmpdir(), "blog"), [["user", "Write the about page"]]);
  assert.equal(lastClaudeChat({ home: dir, cwd: project }), null);
});

test("passwords, API keys and tokens are hidden", () => {
  const text = "use password=hunter2 and sk-ant-api03-abcdefghijklmnopqrstuv, token: ghp_abcdefghijklmnopqrstuvwxyz123456, AKIAABCDEFGHIJKLMNOP";
  const out = redact(text);
  for (const secret of ["hunter2", "sk-ant-api03", "ghp_", "AKIAABCDEFGHIJKLMNOP"]) assert.ok(!out.includes(secret), secret);
  assert.match(out, /password=\[hidden\]/);
});

test("keys from Stripe, Google, npm and GitLab, bearer tokens, URL passwords and private keys are hidden", () => {
  // Built from parts so the made-up keys never look like real ones in this file.
  const fake = (prefix, length) => prefix + "a1B2c3D4".repeat(8).slice(0, length);
  const secrets = [
    fake("sk_" + "live_", 24),
    fake("rk_" + "test_", 24),
    fake("AI" + "za", 35),
    fake("npm" + "_", 36),
    fake("glpat" + "-", 20),
    fake("github" + "_pat_", 40),
    "S3cretPass",
    "hunter2",
    fake("eyJhbGciOi", 30).replace(/\./g, ""),
    "MIIEvQIBADANBgkqhkiG9w0",
  ];
  const text = [
    `stripe ${secrets[0]} and ${secrets[1]}`,
    `google ${secrets[2]}, npm ${secrets[3]}, gitlab ${secrets[4]}, github ${secrets[5]}`,
    `DATABASE_URL=postgres://admin:${secrets[6]}@db.example.com:5432/shop`,
    `my password is ${secrets[7]}`,
    `Authorization: Bearer ${secrets[8]}`,
    `-----BEGIN PRIVATE KEY-----\n${secrets[9]}\n-----END PRIVATE KEY-----`,
  ].join("\n");
  const out = redact(text);
  for (const secret of secrets) assert.ok(!out.includes(secret), secret);
  assert.match(out, /postgres:\/\/admin:\[hidden\]@db\.example\.com/);
  assert.match(out, /my password is \[hidden\]/);
  assert.match(out, /Bearer \[hidden\]/);
});

test("a chat log that disappears while it is read, or cannot be read, is skipped", (t) => {
  const dir = home(t);
  session(dir, "shop", project, [["user", "Fix the cart total"]], 30);
  // A dangling link: listed by readdir, gone by the time it is opened (Claude Code prunes old chats).
  const dangling = path.join(dir, ".claude", "projects", "shop", "gone.jsonl");
  try {
    fs.symlinkSync(path.join(dir, "missing.jsonl"), dangling);
  } catch {
    t.skip("this system cannot create symlinks");
    return;
  }
  assert.equal(lastClaudeChat({ home: dir, cwd: project }).task, "Fix the cart total");
});

test("a chat started in a subfolder of the project counts for the project", (t) => {
  const dir = home(t);
  session(dir, "web", path.join(project, "packages", "web"), [["user", "Fix the header on mobile"]]);
  assert.equal(lastClaudeChat({ home: dir, cwd: project }).task, "Fix the header on mobile");
  assert.equal(lastClaudeChat({ home: dir, cwd: path.join(project, "packages", "api") }), null);
});

test("long messages are shortened to one line", (t) => {
  const dir = home(t);
  session(dir, "shop", project, [["user", `Build the page\n\n${"x".repeat(2000)}`]]);
  const { task } = lastClaudeChat({ home: dir, cwd: project });
  assert.ok(task.length <= 600 && task.endsWith("…") && !task.includes("\n"));
});

test("a chat logged under another spelling of the same folder still matches", (t) => {
  const dir = home(t);
  const real = fs.mkdtempSync(path.join(os.tmpdir(), "waitu-real-"));
  const link = path.join(os.tmpdir(), `waitu-link-${process.pid}`);
  t.after(() => {
    fs.rmSync(link, { force: true, recursive: true });
    fs.rmSync(real, { recursive: true, force: true });
  });
  fs.symlinkSync(real, link, "junction");
  session(dir, "shop", link, [["user", "Fix the header"]]);
  assert.equal(lastClaudeChat({ home: dir, cwd: real }).task, "Fix the header");
});
